def rows_of(art):
    return art.strip("\n").split("\n")


def check(name, art):
    rows = rows_of(art)
    bad = [i for i, r in enumerate(rows) if len(r) != 16]
    if len(rows) != 16 or bad:
        print("  %s: %d rows, rows of another length: %s" % (name, len(rows), bad))


def image(art):
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows_of(art)[:16]):
        for x, ch in enumerate(row[:16]):
            if ch == "#":
                im.putpixel((x, y), (255, 255, 255, 255))
    return im


def sheet(path, names):
    z, cols = 4, 8
    cw, ch = 16 * z + 24, 16 * z + 20
    out = Image.new("RGB", (cols * cw, ((len(names) + cols - 1) // cols) * ch), (12, 11, 18))
    d = ImageDraw.Draw(out)
    for i, k in enumerate(names):
        x, y = (i % cols) * cw + 12, (i // cols) * ch + 4
        out.paste(Image.new("RGB", (16 * z, 16 * z), (232, 120, 60)), (x, y), image(ICONS[k]).resize((16 * z, 16 * z), Image.NEAREST))
        d.text((x - 8, y + 16 * z + 2), k[:14], fill=(200, 200, 200))
    out.save(path)


for k, v in ICONS.items():
    check(k, v)
    image(v).save(os.path.join(G, "tr_" + k + ".png"))
if os.environ.get("SHEET"):
    sheet(os.environ["SHEET"], list(ICONS))
print("stage 43.7 trait pictures: %d" % len(ICONS))

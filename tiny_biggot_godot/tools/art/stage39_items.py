G = os.environ.get("ART_OUT", "assets/graphics/")
OUT = "#140f1c"


def grid(dst, rows, pal):
    w = max(len(r) for r in rows)
    im = Image.new("RGBA", (w, len(rows)), (0, 0, 0, 0))
    p = dict(pal)
    p.setdefault("o", OUT)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in p:
                c = p[ch].lstrip("#")
                im.putpixel((x, y), (int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16), 255))
    im.save(G + dst + ".png")


def M(rows):
    return [r + r[::-1] for r in rows]


def shade(hexc, k):
    c = hexc.lstrip("#")
    r, g, b = (int(c[i:i + 2], 16) for i in (0, 2, 4))
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * k))) for v in (r, g, b))


def tone(base):
    """light / main / dark of a colour: 1, 2, 3."""
    return {"1": shade(base, 1.3), "2": base, "3": shade(base, 0.65)}



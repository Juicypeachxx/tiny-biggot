import os
from PIL import Image

G = os.environ.get("ART_OUT", "assets/graphics/")
OUT = "#140f1c"
WOOD = {"w": "#a8703a", "W": "#7a4a2a", "v": "#c8945a"}
IRON = {"i": "#c8ccd8", "I": "#8b8f9c", "j": "#5a5e6c"}
GOLDC = {"q": "#f2c94c", "Q": "#c8963a", "y": "#fff0b0"}


def grid(dst, rows, pal):
    h = len(rows)
    w = max(len(r) for r in rows)
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in pal:
                c = pal[ch].lstrip("#")
                im.putpixel((x, y), (int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16), 255))
    im.save(G + dst + ".png")


def M(rows):
    """Mirrors 6-character half rows into 12 wide ones."""
    return [r + r[::-1] for r in rows]


def pal(*ds, **extra):
    p = {"o": OUT}
    for d in ds:
        p.update(d)
    p.update(extra)
    return p



def save(name, art):
    rows = [r for r in art.strip("\n").split("\n")]
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            if ch == "#":
                im.putpixel((x, y), (255, 255, 255, 255))
    im.save(G + "tr_" + name + ".png")

for k, v in ICONS.items():
    save(k, v)

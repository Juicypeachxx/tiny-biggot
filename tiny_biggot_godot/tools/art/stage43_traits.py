def rows_of(art):
    return [r for r in art.strip("\n").split("\n")]

def save(name, art, base=None):
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for src in ([base] if base else []) + [art]:
        for y, row in enumerate(rows_of(src)[:16]):
            for x, ch in enumerate(row[:16]):
                if ch == "#":
                    im.putpixel((x, y), (255, 255, 255, 255))
    im.save(G + "tr_" + name + ".png")

for k, v in ICONS.items():
    save(k, v)
for k, v in CORE_MARKS.items():
    save(k, v, HEX)
print("stage 43 trait pictures: %d" % (len(ICONS) + len(CORE_MARKS)))
